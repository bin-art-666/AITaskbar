namespace AIEnter;

internal sealed partial class AiWindow
{
    (int Width, int Height, int Radius, int BottomRadius)? backplateShape;
    AiResizeFrame? resizeFrame;
    bool frameRefreshQueued;
    readonly UISettings backdropSettings = new();
    readonly AccessibilitySettings backdropAccessibility = new();
    readonly SolidColorBrush backplateTint = new();
    (ElementTheme Theme, Color Tint)? taskbarPalette;
    (ElementTheme Theme, Color Tint, string Custom)? effectivePalette;
    PanelTheme.ToolbarPalette? toolbarPalette;

    internal void SetTaskbarPalette(ElementTheme theme, Color tint)
    {
        if (TaskbarFlyout is null || taskbarPalette == (theme, tint)) return;
        taskbarPalette = (theme, tint);
        RefreshBackplateMaterial();
    }

    IEnumerable<ButtonBase> ToolbarButtons() => headerActions.Children.OfType<ButtonBase>()
        .Append(back).Append(providerMore).Concat(providerLabels.Children.OfType<ButtonBase>());

    void ApplyToolbarPalette(ButtonBase button)
    {
        if (toolbarPalette is { } palette) PanelTheme.SetToolbarPalette(button, palette);
    }
    void QueueFrameRefresh()
    {
        if (destroyed || frameRefreshQueued) return;
        frameRefreshQueued = true;
        DispatcherQueue.TryEnqueue(Microsoft.UI.Dispatching.DispatcherQueuePriority.Low, () =>
        {
            if (destroyed) { frameRefreshQueued = false; return; }
            // Presenter changes finish asynchronously and can replace the DWM frame
            // and HRGN after the immediate mode-change callback has completed.
            var handle = WinRT.Interop.WindowNative.GetWindowHandle(this);
            if (Detached) Native.RestoreResizeFrame(handle); else Native.RemoveWindowFrame(handle);
            desktopGlass.ReapplyWindowFrame();
            backplateShape = null;
            RefreshBackplateCorners();
            // Ignore notifications generated by the synchronization itself.
            frameRefreshQueued = false;
        });
    }
    void InitializeBackplateCorners()
    {
        backplate.Background = backplateTint;
        desktopGlass.GlassUnavailable += RefreshBackplateMaterial;
        desktopGlass.WindowSettingsChanged += QueueBackplateMaterialRefresh;
        backdropSettings.AdvancedEffectsEnabledChanged += OnAdvancedEffectsChanged;
        backdropSettings.ColorValuesChanged += OnBackdropColorsChanged;
        PanelTheme.Changed += RefreshBackplateCorners;
        if (TaskbarFlyout is null)
        {
            root.ActualThemeChanged += (_, _) => RefreshBackplateMaterial();
            resizeFrame = new AiResizeFrame(WinRT.Interop.WindowNative.GetWindowHandle(this), () => Detached, QueueFrameRefresh, () => root.CornerRadius);
            Closed += (_, _) => resizeFrame.Dispose();
            AppWindow.Changed += (_, args) =>
            {
                if (args.DidSizeChange || args.DidPositionChange) RefreshBackplateCorners();
            };
        }
        XamlRoot? xamlRoot = null;
        void ScaleChanged(XamlRoot sender, XamlRootChangedEventArgs args) => RefreshBackplateCorners();
        root.Loaded += (_, _) =>
        {
            if (xamlRoot is not null) xamlRoot.Changed -= ScaleChanged;
            xamlRoot = root.XamlRoot;
            if (xamlRoot is not null) xamlRoot.Changed += ScaleChanged;
            RefreshBackplateCorners();
        };
        PanelContent!.SizeChanged += (_, _) => RefreshBackplateCorners();
        aiHeader.SizeChanged += (_, _) => RefreshBackplateCorners();
        Closed += (_, _) =>
        {
            PanelTheme.Changed -= RefreshBackplateCorners;
            desktopGlass.GlassUnavailable -= RefreshBackplateMaterial;
            desktopGlass.WindowSettingsChanged -= QueueBackplateMaterialRefresh;
            backdropSettings.AdvancedEffectsEnabledChanged -= OnAdvancedEffectsChanged;
            backdropSettings.ColorValuesChanged -= OnBackdropColorsChanged;
            if (xamlRoot is not null) xamlRoot.Changed -= ScaleChanged;
        };
        RefreshBackplateCorners();
    }

    void OnAdvancedEffectsChanged(UISettings sender, object args) => QueueBackplateMaterialRefresh();
    void OnBackdropColorsChanged(UISettings sender, object args) => QueueBackplateMaterialRefresh();
    void QueueBackplateMaterialRefresh() => DispatcherQueue.TryEnqueue(RefreshBackplateMaterial);

    void RefreshBackplateMaterial()
    {
        if (destroyed) return;
        var appearance = App.Appearance;
        var tint = PanelTheme.BackplateColor(appearance);
        bool highContrast = backdropAccessibility.HighContrast;
        bool allowTransparency = !highContrast && backdropSettings.AdvancedEffectsEnabled && desktopGlass.CanUseGlass;
        if (highContrast) tint = backdropSettings.GetColorValue(UIColorType.Background);
        else if (!allowTransparency) tint.A = 255;
        var theme = highContrast ? ElementTheme.Default : taskbarPalette?.Theme ?? root.ActualTheme;
        bool dark = theme == ElementTheme.Dark;
        string custom = highContrast ? "" : appearance.BackplateColorFor(dark);
        if (taskbarPalette is not null || custom.Length != 0)
        {
            if (!highContrast && taskbarPalette is { } palette)
            {
                tint.R = palette.Tint.R;
                tint.G = palette.Tint.G;
                tint.B = palette.Tint.B;
            }
            if (effectivePalette != (theme, tint, custom))
            {
                effectivePalette = (theme, tint, custom);
                toolbarPalette = highContrast ? new(dark, tint) : PanelTheme.ResolveToolbarPalette(tint, dark, custom);
                aiHeader.RequestedTheme = theme;
                foreach (var button in ToolbarButtons()) ApplyToolbarPalette(button);
            }
            tint = toolbarPalette!.Tint;
        }
        else if (effectivePalette is not null)
        {
            effectivePalette = null;
            toolbarPalette = null;
            aiHeader.RequestedTheme = ElementTheme.Default;
            foreach (var button in ToolbarButtons()) PanelTheme.SetToolbarPalette(button, null);
        }
        backplateTint.Color = tint;
        float blur = allowTransparency && tint.A < 255 && backplate.Visibility == Visibility.Visible
            ? appearance.BackplateBlur * .18f : 0;
        if (TaskbarFlyout is { } flyout)
            flyout.SetGlass(blur, (float)appearance.BackplateRadius, (float)backplate.Height);
        else desktopGlass.SetBlur(blur);
    }

    void RefreshBackplateCorners()
    {
        if (destroyed) return;
        var handle = WinRT.Interop.WindowNative.GetWindowHandle(this);
        int width = AppWindow.Size.Width, height = AppWindow.Size.Height;
        if (TaskbarFlyout is null && (width <= 0 || height <= 0)) return;
        // The page owns the lower silhouette. A full-window glass surface behind
        // its larger web corners leaves visible tinted wedges, even when clipped.
        pageFrame.Margin = new Thickness(-root.Padding.Left, 0, -root.Padding.Right, -root.Padding.Bottom);
        var host = PanelContent!;
        float canvasWidth = (float)host.ActualWidth, canvasHeight = (float)host.ActualHeight;
        double webRadius = AiPolicy.CornerRadius(cornerPreview ?? options.Data,
            PanelTheme.Value<CornerRadius>("CardRadius").TopLeft, canvasWidth, canvasHeight);
        double headerBottom = root.Padding.Top + aiHeader.Margin.Top + aiHeader.ActualHeight + root.RowSpacing;
        backplate.Height = Math.Max(App.Appearance.BackplateRadius, headerBottom + webRadius);
        root.CornerRadius = new CornerRadius(App.Appearance.BackplateRadius, App.Appearance.BackplateRadius, webRadius, webRadius);
        backplate.CornerRadius = new CornerRadius(App.Appearance.BackplateRadius, App.Appearance.BackplateRadius, 0, 0);
        desktopGlass.SetShape(new Vector2(canvasWidth, canvasHeight),
            new Vector2(canvasWidth, Math.Min(canvasHeight, (float)backplate.Height)),
            (float)App.Appearance.BackplateRadius, squareBottom: true);
        RefreshBackplateMaterial();
        // Grid.CornerRadius only rounds its own paint. Clip the complete content
        // visual so external glass and WebView composition layers cannot leak.
        ((Microsoft.UI.Xaml.Controls.Border)host).CornerRadius = root.CornerRadius;
        if (host.ActualWidth > 0 && host.ActualHeight > 0)
        {
            var visual = Microsoft.UI.Xaml.Hosting.ElementCompositionPreview.GetElementVisual(host);
            var clip = visual.Compositor.CreateRectangleClip();
            clip.Left = clip.Top = 0; clip.Right = (float)host.ActualWidth; clip.Bottom = (float)host.ActualHeight;
            clip.TopLeftRadius = clip.TopRightRadius = new System.Numerics.Vector2((float)App.Appearance.BackplateRadius);
            clip.BottomLeftRadius = clip.BottomRightRadius = new System.Numerics.Vector2((float)webRadius);
            var previous = visual.Clip;
            visual.Clip = clip;
            previous?.Dispose();
        }
        if (TaskbarFlyout is not null) return;
        double scale = Native.GetDpiForWindow(handle) / 96d;
        int radius = Math.Min(Math.Min(width, height) / 2, (int)Math.Round(App.Appearance.BackplateRadius * scale));
        int bottomRadius = (int)Math.Round(webRadius * scale);
        if (backplateShape == (width, height, radius, bottomRadius)) return;
        // Clip the native window as well as its XAML content: acrylic must not
        // remain visible behind the transparent corners. Windows owns a set HRGN.
        var region = CreateSilhouette(width, height, radius, bottomRadius);
        if (region == IntPtr.Zero) throw new InvalidOperationException("无法创建背板圆角区域。");
        if (SetWindowRgn(handle, region, true) == 0)
        {
            DeleteObject(region);
            throw new InvalidOperationException("无法应用背板圆角区域。");
        }
        backplateShape = (width, height, radius, bottomRadius);
    }
    internal void VerifyBackplateCorners()
    {
        if (!ReferenceEquals(SystemBackdrop, desktopGlass) || !desktopGlass.IsReady)
            throw new Exception("The window did not attach its masked desktop backdrop.");
        var tint = PanelTheme.BackplateColor(App.Appearance);
        bool shouldBlur = !backdropAccessibility.HighContrast && backdropSettings.AdvancedEffectsEnabled
            && tint.A < 255 && App.Appearance.BackplateBlur > 0;
        if (desktopGlass.HasGlass != shouldBlur || backplate.CornerRadius.TopLeft != App.Appearance.BackplateRadius
            || Math.Abs(desktopGlass.MaskSize.X - backplate.ActualWidth) > 1
            || Math.Abs(desktopGlass.MaskSize.Y - backplate.ActualHeight) > 1)
            throw new Exception("The desktop mask is not synchronized with its rounded tint surface.");
        if (Math.Abs(backplate.ActualWidth - ((FrameworkElement)Content).ActualWidth) > 1
            || backplate.ActualHeight >= ((FrameworkElement)Content).ActualHeight / 2)
            throw new Exception("Glass still covers the conversation perimeter.");
        var pageOrigin = pageFrame.TransformToVisual((UIElement)Content).TransformPoint(new());
        if (Math.Abs(pageOrigin.X) > 1 || Math.Abs(pageFrame.ActualWidth - ((FrameworkElement)Content).ActualWidth) > 1
            || Math.Abs(pageOrigin.Y + pageFrame.ActualHeight - ((FrameworkElement)Content).ActualHeight) > 1)
            throw new Exception("The page is not flush with the window sides and bottom.");
        var host = (Microsoft.UI.Xaml.Controls.Border)Content;
        var clip = Microsoft.UI.Xaml.Hosting.ElementCompositionPreview.GetElementVisual(host).Clip as Microsoft.UI.Composition.RectangleClip;
        if (clip == null || clip.TopLeftRadius.X != App.Appearance.BackplateRadius
            || clip.BottomLeftRadius.X != host.CornerRadius.BottomLeft
            || Math.Abs(clip.Right - host.ActualWidth) > 1 || Math.Abs(clip.Bottom - host.ActualHeight) > 1)
            throw new Exception("The full content composition layer is not clipped to the rounded silhouette.");
        var handle = WinRT.Interop.WindowNative.GetWindowHandle(this);
        var origin = new Native.Point(); ClientToScreen(handle, ref origin);
        GetBackplateWindowRect(handle, out var bounds); GetBackplateClientRect(handle, out var client);
        if (origin.X != bounds.Left || origin.Y != bounds.Top || client.Right != AppWindow.Size.Width || client.Bottom != AppWindow.Size.Height)
            throw new Exception("System non-client frame changed the visible backplate bounds.");
        var region = CreateRoundRectRgn(0, 0, 1, 1, 0, 0);
        try
        {
            if (GetWindowRgn(WinRT.Interop.WindowNative.GetWindowHandle(this), region) == 0)
                throw new Exception("Native backplate clip is missing.");
            var shape = backplateShape!.Value;
            int w = shape.Width, h = shape.Height, r = shape.Radius;
            if (w != AppWindow.Size.Width || h != AppWindow.Size.Height) throw new Exception("Backplate clip retained its previous size.");
            var expected = CreateSilhouette(w, h, r, shape.BottomRadius);
            try { if (!EqualRgn(region, expected)) throw new Exception("Native backplate no longer uses the configured circular corners."); }
            finally { DeleteObject(expected); }
            if (Detached) resizeFrame!.VerifyEdges();
            if (PtInRegion(region, 0, 0) || PtInRegion(region, w - 1, 0)
                || PtInRegion(region, 0, h - 1) || PtInRegion(region, w - 1, h - 1)
                || !PtInRegion(region, r, 1) || !PtInRegion(region, w / 2, h / 2)
                || !PtInRegion(region, 1, h / 2))
                throw new Exception("Backplate corners are not transparent or the window interior was clipped.");
            if (root.CornerRadius.TopLeft != App.Appearance.BackplateRadius)
                throw new Exception("Backplate preview did not apply the current radius.");
        }
        finally { DeleteObject(region); }
    }
    static IntPtr CreateSilhouette(int width, int height, int topRadius, int bottomRadius)
    {
        var result = CreateRoundRectRgn(0, 0, width + 1, height + 1, topRadius * 2, topRadius * 2);
        var lower = CreateRoundRectRgn(0, 0, width + 1, height + 1, bottomRadius * 2, bottomRadius * 2);
        var half = CreateRectRgn(0, 0, width + 1, height / 2);
        try
        {
            if (result == IntPtr.Zero || lower == IntPtr.Zero || half == IntPtr.Zero
                || CombineRgn(result, result, half, 1) == 0) throw new Exception("无法创建顶部圆角轮廓。");
            SetRectRgn(half, 0, height / 2, width + 1, height + 1);
            if (CombineRgn(lower, lower, half, 1) == 0 || CombineRgn(result, result, lower, 2) == 0)
                throw new Exception("无法创建底部圆角轮廓。");
            return result;
        }
        catch { if (result != IntPtr.Zero) DeleteObject(result); throw; }
        finally { if (lower != IntPtr.Zero) DeleteObject(lower); if (half != IntPtr.Zero) DeleteObject(half); }
    }
    [DllImport("gdi32.dll")] static extern IntPtr CreateRectRgn(int left, int top, int right, int bottom);
    [DllImport("gdi32.dll")] static extern bool SetRectRgn(IntPtr region, int left, int top, int right, int bottom);
    [DllImport("gdi32.dll")] static extern int CombineRgn(IntPtr destination, IntPtr first, IntPtr second, int mode);
    [DllImport("user32.dll", EntryPoint = "GetWindowRect")] static extern bool GetBackplateWindowRect(IntPtr window, out Native.Rect rect);
    [DllImport("user32.dll", EntryPoint = "GetClientRect")] static extern bool GetBackplateClientRect(IntPtr window, out Native.Rect rect);
    [DllImport("gdi32.dll")] static extern bool EqualRgn(IntPtr first, IntPtr second);
    [DllImport("gdi32.dll")] static extern IntPtr CreateRoundRectRgn(int left, int top, int right, int bottom, int ellipseWidth, int ellipseHeight);
    [DllImport("user32.dll")] static extern int SetWindowRgn(IntPtr window, IntPtr region, bool redraw);
    [DllImport("user32.dll")] static extern int GetWindowRgn(IntPtr window, IntPtr region);
    [DllImport("gdi32.dll")] static extern bool PtInRegion(IntPtr region, int x, int y);
    [DllImport("gdi32.dll")] static extern bool DeleteObject(IntPtr value);
}
